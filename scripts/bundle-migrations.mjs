/**
 * Bundle every migration into one file.
 *
 * `npm run db:migrate:remote` is the supported way to apply the schema, and it
 * needs the Wrangler CLI and a Cloudflare login. Somebody setting up from the
 * dashboard alone has no CLI, and the D1 console takes pasted SQL — so this
 * produces one file to paste.
 *
 * It is a convenience, not a migration: it writes nothing to `d1_migrations`,
 * so wrangler does not know it ran. That caveat is in the generated header
 * because the file will be read by someone who never opened this script.
 *
 *   node scripts/bundle-migrations.mjs            # write it
 *   node scripts/bundle-migrations.mjs --check    # is it current?
 *
 * scripts/build.mjs runs --check, so the bundle cannot drift from the
 * migrations it claims to contain.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = 'database/migrations';
const TARGET = 'database/bundled/schema.sql';

export function buildBundle() {
  const files = readdirSync(SOURCE).filter(f => f.endsWith('.sql')).sort();

  const header = `-- ---------------------------------------------------------------------------
-- Meet Millions Finance CRM — the full schema, all ${files.length} migrations in order.
--
-- GENERATED by scripts/bundle-migrations.mjs. Do not edit by hand; edit the
-- files in ${SOURCE}/ and regenerate.
--
-- This exists for one situation: applying the schema to a brand-new, empty D1
-- database through the Cloudflare dashboard console, where there is no CLI.
-- The supported path is still
--
--     npm run db:migrate:remote
--
-- which records each file in d1_migrations so later migrations apply cleanly.
--
-- THIS FILE DOES NOT WRITE d1_migrations. Wrangler will therefore believe none
-- of these migrations has run, and a later db:migrate:remote will try to apply
-- all of them again against tables that already exist, and fail. If you paste
-- this, keep using the dashboard for subsequent schema changes, or reconcile
-- d1_migrations by hand before going back to the CLI.
--
-- Apply to an EMPTY database only.
-- ---------------------------------------------------------------------------
`;

  const bodies = files.map(name => {
    const sql = readFileSync(join(SOURCE, name), 'utf8').trim();
    return `\n-- ===== ${name} =====\n\n${sql}\n`;
  });

  return { text: header + bodies.join(''), count: files.length };
}

const { text, count } = buildBundle();
const check = process.argv.includes('--check');
const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : null;

if (check) {
  if (current === text) {
    console.log(`  ${TARGET} is current (${count} migrations).`);
    process.exit(0);
  }
  console.error(`\n  ${TARGET} is ${current === null ? 'missing' : 'stale'}.`);
  console.error('  Run: node scripts/bundle-migrations.mjs\n');
  process.exit(1);
}

mkdirSync('database/bundled', { recursive: true });
writeFileSync(TARGET, text);
console.log(`  Wrote ${TARGET} — ${count} migrations, ${(text.length / 1024).toFixed(1)} KiB.`);
