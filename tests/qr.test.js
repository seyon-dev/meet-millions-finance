test('QR: every fixture matches the reference matrix exactly', () => {
  for (const fixture of FIXTURES) {
    const matrix = encodeQr(fixture.text);
    const rows = matrix.map(row => row.map(cell => (cell ? '#' : '.')).join(''));

    assert.equal(rows.length, fixture.rows.length,
      `${fixture.note}: expected a version ${fixture.version} grid`);

    for (const [i, row] of rows.entries()) {
      assert.equal(row, fixture.rows[i],
        `${fixture.note}: row ${i} differs from the reference`);
    }
  }
});

test('QR: the version grows with the data, and stops where the encoder does', () => {
  const versionOf = text => (encodeQr(text).length - 17) / 4;

  assert.equal(versionOf('x'.repeat(17)), 1, '17 bytes is exactly version 1');
  assert.equal(versionOf('x'.repeat(18)), 2, 'one byte more needs version 2');
  assert.equal(versionOf('x'.repeat(271)), 10, '271 bytes is exactly version 10');

  assert.throws(() => encodeQr('x'.repeat(272)),
    /too long/, 'past version 10 it refuses rather than producing something unreadable');
});

test('QR: the function patterns are where the specification puts them', () => {
  const matrix = encodeQr('otpauth://totp/x?secret=JBSWY3DPEHPK3PXP');
  const size = matrix.length;

  // The three finder patterns: a dark 7x7 ring with a dark 3x3 core.
  for (const [row, col] of [[0, 0], [0, size - 7], [size - 7, 0]]) {
    assert.equal(matrix[row][col], true, 'finder corner is dark');
    assert.equal(matrix[row + 1][col + 1], false, 'the ring has a light gap');
    assert.equal(matrix[row + 3][col + 3], true, 'the core is dark');
  }

  // The timing patterns alternate, starting dark at module 8.
  for (let i = 8; i < size - 8; i += 1) {
    assert.equal(matrix[6][i], i % 2 === 0, `horizontal timing at ${i}`);
    assert.equal(matrix[i][6], i % 2 === 0, `vertical timing at ${i}`);
  }

  assert.equal(matrix[size - 8][8], true, 'the always-dark module is dark');
});
